#!/usr/bin/env python3
"""Plan copying herdr sessions into herdr-app spaces. DRY RUN ONLY: it prints, never runs.

Run ON YOUR MAC, where the herdr-app window is. `herdr-app do` drives a window, and the
VM has none; `--machine` puts every new terminal on the VM's herdr-core, so the copies run
there exactly like the herdr originals did.

    ./mac/herdr-to-hc.py --from __VM_NAME__            # read the VM's herdr sessions over ssh
    ./mac/herdr-to-hc.py                            # read ~/.config/herdr here (on the VM)
    ./mac/herdr-to-hc.py --from __VM_NAME__ --only NetSapiens --only web

Mapping. herdr nests session > workspace > tab; herdr-app has only space > tab, so each
herdr WORKSPACE becomes a space named "<session> · <workspace>" ("<session>" alone when
the two match). Tabs keep their names and working directories. The `default` session is
skipped. No herdr tab is split, so there is no layout to rebuild; a split tab is reported
and only its first pane is copied.

Agents. A tab where herdr recorded a Claude session ID is copied as a FORK
(`claude --resume <id> --fork-session`): the copy gets a new session ID and the herdr
original is left untouched, so both can be compared and both can run at once. By default
the tab only PRINTS that command in a shell, so creating 20 tabs does not start 20 Claude
processes on the VM at once; --start-agents runs it instead.

Not verified: what `space.new` prints. herdr-app's guide says it returns the created IDs
as JSON, but the key holding the space ID could not be checked without a window. The
emitted script reads `.space` and stops if that is empty -- confirm with one
`herdr-app do space.new` before trusting it.
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

SESSIONS = "~/.config/herdr/sessions"


def load(host: str | None) -> dict[str, dict]:
    """{session name: parsed session.json}, read locally or over one ssh call."""
    if host is None:
        out = {}
        for f in sorted(Path(os.path.expanduser(SESSIONS)).glob("*/session.json")):
            out[f.parent.name] = json.loads(f.read_text())
        return out
    # NUL-separated name/body pairs: names and JSON can hold anything but NUL.
    remote = (f'cd {SESSIONS} && for d in */; do [ -f "$d/session.json" ] || continue; '
              'printf "%s\\0" "${d%/}"; cat "$d/session.json"; printf "\\0"; done')
    raw = subprocess.run(["ssh", host, remote], capture_output=True, check=True).stdout
    parts = raw.decode().split("\0")
    return {parts[i]: json.loads(parts[i + 1]) for i in range(0, len(parts) - 1, 2)}


def plan(sessions: dict[str, dict], only: set[str]) -> list[dict]:
    spaces = []
    for sess, data in sorted(sessions.items(), key=lambda kv: kv[0].lower()):
        if sess == "default" or (only and sess not in only):
            continue
        for w in data.get("workspaces") or []:
            ws = w.get("custom_name") or Path(w.get("identity_cwd") or "").name or w.get("id", "")
            name = sess if ws.lower() == sess.lower() else f"{sess} · {ws}"
            tabs = []
            for i, t in enumerate(w.get("tabs") or [], 1):
                panes = t.get("panes") or {}
                first = panes[str(t.get("root_pane"))] if str(t.get("root_pane")) in panes \
                    else next(iter(panes.values()), {})
                agent = first.get("agent_session") or {}
                tabs.append({
                    "name": t.get("custom_name") or f"tab {i}",
                    "folder": first.get("cwd") or w.get("identity_cwd") or "~",
                    "agent": agent.get("agent") or "",
                    "resume": agent.get("value") if agent.get("kind") == "id" else "",
                    "split": len(panes) > 1,
                })
            if tabs:
                spaces.append({"session": sess, "name": name, "tabs": tabs})
    return spaces


def argv_for(tab: dict, start: bool) -> list[str] | None:
    if tab["agent"] != "claude" or not tab["resume"]:
        return None                       # plain shell in the tab's folder
    cmd = ["claude", "--resume", tab["resume"], "--fork-session"]
    if start:
        return cmd
    line = shlex.join(cmd)
    return ["bash", "-lc", f"printf '%s\\n' {shlex.quote('To fork: ' + line)}; exec bash -l"]


def emit(spaces: list[dict], machine: str, start: bool) -> None:
    q = lambda d: shlex.quote(json.dumps(d, ensure_ascii=False))
    print("#!/usr/bin/env bash")
    print("# Generated by herdr-to-hc.py -- review before running. Needs jq and an open window.")
    print("set -euo pipefail")
    print("space_id() { jq -r '.space // empty'; }   # UNVERIFIED key; see the script's notes")
    for s in spaces:
        print(f"\n# --- {s['name']}  (herdr session {s['session']}, {len(s['tabs'])} tabs)")
        first, rest = s["tabs"][0], s["tabs"][1:]
        args = {"name": s["name"], "machine": machine, "folder": first["folder"],
                "tab": first["name"]}
        if (a := argv_for(first, start)):
            args["argv"] = a
        print(f"sp=$(herdr-app do space.new {q(args)} | space_id)")
        print(f'[ -n "$sp" ] || {{ echo "no space id for {s["name"]}" >&2; exit 1; }}')
        for t in rest:
            targs = {"space": "__SP__", "name": t["name"], "folder": t["folder"]}
            if (a := argv_for(t, start)):
                targs["argv"] = a
            # The space id is only known at run time; splice it into the JSON there.
            print(f'herdr-app do tab.new "$(printf %s {q(targs)} | sed "s/__SP__/$sp/")"')


def summary(spaces: list[dict]) -> None:
    tabs = [t for s in spaces for t in s["tabs"]]
    forks = [t for t in tabs if argv_for(t, True)]
    other = [t for t in tabs if t["agent"] and t["agent"] != "claude"]
    print(f"{len(spaces)} spaces, {len(tabs)} tabs, {len(forks)} Claude forks", file=sys.stderr)
    for s in spaces:
        print(f"  {s['name']}", file=sys.stderr)
        for t in s["tabs"]:
            mark = "fork" if argv_for(t, True) else (t["agent"] or "shell")
            warn = "  [split: first pane only]" if t["split"] else ""
            print(f"      {t['name']:<28} {mark:<6} {t['folder']}{warn}", file=sys.stderr)
    if other:
        print(f"  {len(other)} non-Claude agent tabs become plain shells", file=sys.stderr)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--from", dest="host", help="ssh host holding the herdr sessions")
    p.add_argument("--machine", default="__VM_NAME__",
                   help="herdr-app machine label for the VM (hc machine ls on the Mac)")
    p.add_argument("--only", action="append", default=[], help="herdr session (repeatable)")
    p.add_argument("--start-agents", action="store_true",
                   help="run the Claude forks instead of printing their commands")
    a = p.parse_args()
    spaces = plan(load(a.host), set(a.only))
    summary(spaces)                       # stderr: the readable plan
    emit(spaces, a.machine, a.start_agents)   # stdout: the commands, to review or save


if __name__ == "__main__":
    main()
